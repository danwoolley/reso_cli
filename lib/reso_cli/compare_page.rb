    CSS

    JS = <<~'JS'.freeze
      (function () {
        const rows = [...document.querySelectorAll("tbody tr")], filter = document.getElementById("filter");
        const showSame = document.getElementById("show-same"), noMatch = document.getElementById("no-match");
        let only = null; // a single status picked from the summary cards
        function apply() {
          const q = filter.value.trim().toLowerCase();
          let shown = 0;
          rows.forEach(r => {
            const st = r.dataset.status;
            let ok = only ? st === only : (st !== "same" || showSame.checked);
            if (q && !r.dataset.search.includes(q)) ok = false;
            r.classList.toggle("hide", !ok);
            if (ok) shown++;
          });
          noMatch.hidden = shown > 0;
          document.querySelectorAll(".card").forEach(c => c.classList.toggle("active", c.dataset.show === only));
        }
        document.querySelectorAll(".card").forEach(c => c.onclick = () => { only = only === c.dataset.show ? null : c.dataset.show; apply(); });
        document.getElementById("reset").onclick = () => { only = null; showSame.checked = false; filter.value = ""; apply(); };
        filter.addEventListener("input", apply);
        showSame.onchange = apply;
        apply();
      })();
    JS
  end
end
