require "time"

module ResoCli
  # Builds a Markdown report comparing a set of listings between two feeds:
  # which listings are missing from each side (and why), status mismatches,
  # and which fields disagree most often.
  module CompareReport
    module_function

    def id_of(record) = record["ListingId"].to_s

    def time_of(value)
      case value
      when DateTime, Time then value.to_time.utc
      when String then Time.iso8601(value).utc
      end
    rescue ArgumentError
      nil
    end

    def minutes(seconds) = (seconds / 60.0).round

    # Why a listing that's in `side` is missing from `other_name`.
    # `other` is that listing as found in the other feed by MLS number alone (nil if not there at all).
    # `filters` are the query's --eq filters, e.g. { "City" => "Irvine" }. A field given several
    # values, e.g. { "StandardStatus" => ["Active", "Pending"] }, matches any of them.
    def missing_reason(present, other, other_name, filters, other_pulled_at)
      if other.nil? && present["InternetEntireListingDisplayYN"] == false
        return { reason: "Not approved for internet display (InternetEntireListingDisplayYN = No); #{other_name} doesn't include these" }
      end
      return { reason: "Not in #{other_name} at all" } if other.nil?

      if other["InternetEntireListingDisplayYN"] == false || present["InternetEntireListingDisplayYN"] == false
        return { reason: "Not approved for internet display (InternetEntireListingDisplayYN = No)" }
      end

      mismatched = filters.filter_map do |field, value|
        next if Array(value).any? { |one| other[field].to_s.casecmp?(one.to_s) }

        "#{field} is #{other[field].inspect} in #{other_name}"
      end
      if mismatched.any?
        result = { reason: mismatched.join("; ") }
        changed_at = time_of(other["ModificationTimestamp"])
        present_changed = time_of(present["ModificationTimestamp"])
        if changed_at && present_changed && changed_at > present_changed && other_pulled_at
          result[:changed_at] = changed_at
        end
        return result
      end

      { reason: "In #{other_name} and matches the query; it probably changed between the two pulls" }
    end

    # Tally field comparison results across all matched listings
    def field_stats(pairs)
      stats = Hash.new { |h, k| h[k] = { different: 0, format: 0, only_a: 0, only_b: 0, example: nil } }
      list_values = Hash.new { |h, k| h[k] = { only_a: Hash.new(0), only_b: Hash.new(0) } }
      totals = Hash.new(0)

      pairs.each do |a, b|
        Compare.compare(a, b).each do |row|
          totals[row[:status]] += 1
          next if %i[same system].include?(row[:status])

          s = stats[row[:field]]
          s[row[:status]] += 1
          s[:example] ||= { id: id_of(a), a: row[:a], b: row[:b] } if row[:status] == :different
          diff = row[:status] == :different ? ComparePage.list_diff(row[:a], row[:b]) : nil
          next unless diff

          diff[:only_a].each { |v| list_values[row[:field]][:only_a][v] += 1 }
          diff[:only_b].each { |v| list_values[row[:field]][:only_b][v] += 1 }
        end
      end
      { fields: stats, list_values: list_values, totals: totals }
    end

    def short(value, max = 60)
      text = Compare.empty?(value) ? "—" : DetailPage.text("x", value)
      text = text.gsub("|", "\\|").gsub(/\s+/, " ")
      text.length > max ? "#{text[0, max - 1]}…" : text
    end

    def ts(time) = time ? time.utc.strftime("%Y-%m-%d %H:%M:%S UTC") : "—"

    def build(a_name:, b_name:, a_records:, b_records:, lookups_in_a:, lookups_in_b:, meta:)
      a_by_id = a_records.to_h { |r| [id_of(r), r] }
      b_by_id = b_records.to_h { |r| [id_of(r), r] }
      matched = (a_by_id.keys & b_by_id.keys)
      only_a = a_by_id.keys - b_by_id.keys
      only_b = b_by_id.keys - a_by_id.keys
      filters = meta[:filters] || {}
      pairs = matched.map { |id| [a_by_id[id], b_by_id[id]] }
      stats = field_stats(pairs)
      status_mismatch = pairs.reject { |a, b| a["StandardStatus"].to_s == b["StandardStatus"].to_s }

      out = []
      out << "# Feed comparison: #{a_name} vs. #{b_name}"
      out << ""
      out << "Generated by reso_cli on #{ts(meta[:generated_at])}."
      out << ""
      out << "## Summary"
      out << ""
      out << "| | #{a_name} | #{b_name} |"
      out << "|---|---|---|"
      out << "| Listings returned | #{a_records.size} | #{b_records.size} |"
      out << "| In both feeds (matched on `ListingId`) | #{matched.size} | #{matched.size} |"
      out << "| Only in this feed | #{only_a.size} | #{only_b.size} |"
      out << "| Pull finished | #{ts(meta[:a_pulled_at])} | #{ts(meta[:b_pulled_at])} |"
      out << ""
      compared = stats[:totals].values.sum - stats[:totals][:system]
      if compared.positive?
        agree = stats[:totals][:same] + stats[:totals][:format]
        in_both = agree + stats[:totals][:different]
        out << "Across the #{matched.size} matched listings, where **both** feeds have a value, **#{(100.0 * agree / in_both).round(1)}%** of values agree " \
               "(#{stats[:totals][:same]} identical, #{stats[:totals][:format]} same value in a different format) and " \
               "#{stats[:totals][:different]} differ. Another #{stats[:totals][:only_a]} values are only in #{a_name} and " \
               "#{stats[:totals][:only_b]} only in #{b_name}. Counting those, #{(100.0 * agree / compared).round(1)}% of all values agree. " \
               "System fields (keys, IDs, each system's own timestamps) are excluded."
        out << ""
      end
      out << "**Status mismatches:** #{status_mismatch.size} matched listing(s) have a different `StandardStatus` in each feed." if matched.any?
      out << ""
      if meta[:requested_ids]
        not_found = meta[:requested_ids].uniq - a_by_id.keys - b_by_id.keys
        if not_found.any?
          out << "**Not found in either feed (#{not_found.size}):** #{not_found.join(', ')}"
          out << ""
        end
      end

      out << "## Systems and method"
      out << ""
      out << "| | #{a_name} | #{b_name} |"
      out << "|---|---|---|"
      out << "| Endpoint | `#{meta[:a_endpoint]}` | `#{meta[:b_endpoint]}` |"
      out << ""
      out << "- **Listings compared:** #{meta[:selection]}"
      out << "- **Records** were matched on `ListingId` (the MLS number). Each system assigns its own `ListingKey`, so keys aren't comparable."
      out << "- **Missing listings** were looked up in the other feed by MLS number alone, with no other filters, to find out why they're missing."
      out << "- **Field comparison** treats values as the same format if they only differ in case, spacing, punctuation, a URL's `http(s)://`, list order, or numbers sent as text."
      out << "- **Capped:** stopped at the --max limit of #{meta[:max]} listings per feed; not every match was compared." if meta[:capped]
      out << ""

      [[a_name, b_name, only_a, a_by_id, lookups_in_b, meta[:b_pulled_at]], [b_name, a_name, only_b, b_by_id, lookups_in_a, meta[:a_pulled_at]]].each do |name, other_name, ids, by_id, lookups, other_pulled|
        out << "## Only in #{name} (#{ids.size})"
        out << ""
        if ids.empty?
          out << "None."
          out << ""
          next
        end
        reasons = ids.map do |id|
          present = by_id[id]
          other = lookups[id]
          info = lookups.key?(id) ? missing_reason(present, other, other_name, filters, other_pulled) : { reason: "Not looked up (over the lookup limit)" }
          [id, present, other, info]
        end
        reasons.group_by { |_, _, _, info| info[:reason].sub(/ is .*/, " differs") }.each do |group, list|
          out << "- #{group}: #{list.size}"
        end
        out << ""
        out << "| MLS # | Address | #{name} status | #{other_name} status | Why it's missing from #{other_name} | #{other_name} changed | Not yet in #{name} after |"
        out << "|---|---|---|---|---|---|---|"
        reasons.each do |id, present, other, info|
          lag = info[:changed_at] && other_pulled ? "≥ #{minutes(meta[name == a_name ? :a_pulled_at : :b_pulled_at] - info[:changed_at])} min" : ""
          lag = "" if lag.include?("-")
          out << "| #{id} | #{short(Slideshow.address(present), 40)} | #{short(present['StandardStatus'], 20)} | #{other ? short(other['StandardStatus'], 20) : 'not found'} | #{short(info[:reason], 90)} | #{info[:changed_at] ? ts(info[:changed_at]) : ''} | #{lag} |"
        end
        out << ""
      end

      if status_mismatch.any?
        out << "## Status mismatches among matched listings (#{status_mismatch.size})"
        out << ""
        out << "| MLS # | Address | #{a_name} status | #{a_name} modified | #{b_name} status | #{b_name} modified |"
        out << "|---|---|---|---|---|---|"
        status_mismatch.each do |a, b|
          out << "| #{id_of(a)} | #{short(Slideshow.address(a), 40)} | #{short(a['StandardStatus'], 20)} | #{ts(time_of(a['ModificationTimestamp']))} | #{short(b['StandardStatus'], 20)} | #{ts(time_of(b['ModificationTimestamp']))} |"
        end
        out << ""
      end

      if matched.any?
        rows = stats[:fields].map { |field, s| [field, s, s[:different] + s[:only_a] + s[:only_b]] }
        differing = rows.select { |_, s, _| s[:different].positive? }.sort_by { |f, s, _| [-s[:different], f] }
        out << "## Fields that differ most often"
        out << ""
        if differing.empty?
          out << "No field values differ."
        else
          out << "| Field | Listings that differ | Same value, different format | Example (MLS #: #{a_name} → #{b_name}) |"
          out << "|---|---|---|---|"
          differing.first(30).each do |field, s, _|
            ex = s[:example]
            example = ex ? "#{ex[:id]}: #{short(ex[:a], 40)} → #{short(ex[:b], 40)}" : ""
            out << "| `#{field}` | #{s[:different]} of #{matched.size} | #{s[:format]} | #{example} |"
          end
        end
        out << ""

        lists = stats[:list_values].flat_map do |field, sides|
          sides[:only_a].map { |v, n| [field, v, a_name, n] } + sides[:only_b].map { |v, n| [field, v, b_name, n] }
        end.sort_by { |f, v, _, n| [-n, f, v] }
        if lists.any?
          out << "## List values present in only one feed"
          out << ""
          out << "Values inside list fields (features, room types, terms…) that one feed includes and the other leaves out, for the same listing."
          out << ""
          out << "| Field | Value | Only in | Listings |"
          out << "|---|---|---|---|"
          lists.first(40).each { |field, value, side, n| out << "| `#{field}` | #{short(value, 50)} | #{side} | #{n} |" }
          out << ""
        end

        one_sided = rows.select { |_, s, _| s[:only_a].positive? || s[:only_b].positive? }
        a_only_fields = one_sided.select { |_, s, _| s[:only_a] >= s[:only_b] }.sort_by { |f, s, _| [-s[:only_a], f] }
        b_only_fields = one_sided.select { |_, s, _| s[:only_b] > s[:only_a] }.sort_by { |f, s, _| [-s[:only_b], f] }
        out << "## Fields filled in by only one feed"
        out << ""
        out << "Fields with a value in one feed and empty or absent in the other, with the number of matched listings where that happens."
        out << ""
        out << "- **Mostly only in #{a_name}:** " + (a_only_fields.empty? ? "none" : a_only_fields.first(40).map { |f, s, _| "`#{f}` (#{s[:only_a]})" }.join(", "))
        out << "- **Mostly only in #{b_name}:** " + (b_only_fields.empty? ? "none" : b_only_fields.first(40).map { |f, s, _| "`#{f}` (#{s[:only_b]})" }.join(", "))
        out << ""
      end

      out.join("\n")
    end
  end
end
